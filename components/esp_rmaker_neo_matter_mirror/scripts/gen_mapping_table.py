# Widths of the generated table fields. A list length and a narrowed scalar are this port's
# constraints, not the mapping language's, so the checks live with the descriptors that emit them.
U8_MAX = 0xFF


def check_count(where, what, count, errors):
    """The tables hold list lengths in a uint8_t."""
    if count > U8_MAX:
        errors.append(f"{where}: {what} has {count} entries, more than {U8_MAX}")


def check_u8(where, what, value, errors):
    if isinstance(value, int) and not 0 <= value <= U8_MAX:
        errors.append(f"{where}: {what} {value} does not fit a uint8")



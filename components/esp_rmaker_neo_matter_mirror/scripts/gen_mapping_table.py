def _hex(value):
    """Parse a JSON hex-string id (e.g. "0x0300") into an int.

    Matter ids are 32-bit: a manufacturer extension carries the vendor in the upper
    half, so the tables keep the full width rather than assuming standard ids.
    """
    if not isinstance(value, str) or not value.startswith("0x"):
        raise ValueError(f"expected hex string like '0x0300', got {value!r}")
    parsed = int(value, 16)
    if not 0 <= parsed <= U32_MAX:
        raise ValueError(f"id {value} does not fit a 32-bit Matter id")
    return parsed


def _check_count(where, what, count, errors):
    """The tables hold list lengths in a uint8_t."""
    if count > U8_MAX:
        errors.append(f"{where}: {what} has {count} entries, more than {U8_MAX}")


def _check_i32(where, what, value, errors):
    """Values crossing the transform pipeline are int32 end to end (the port reduces
    every Matter numeric to int32), so a mapping constant must fit that."""
    if not isinstance(value, int):
        return
    if not I32_MIN <= value <= I32_MAX:
        errors.append(f"{where}: {what} {value} does not fit an int32")


def _check_u8(where, what, value, errors):
    if isinstance(value, int) and not 0 <= value <= U8_MAX:
        errors.append(f"{where}: {what} {value} does not fit a uint8")



def _quoted(value):
    return "NULL" if value is None else '"%s"' % value


def _boolean(value):
    return "true" if value else "false"


def _hex8(value):
    return "0x%08X" % value


def _hex4(value):
    return "0x%04X" % value


def _hex2(value):
    return "0x%02X" % value


class Scalar:
    """One generated struct field: its C declaration, where it reads from in a JSON
    entry, how it renders, and the width check its C type implies.
    """

    def __init__(self, name, get, render=str, check=None, width=None, note=None):
        self.name = name
        self.get = get
        self.render = render
        self.check = check
        self.width = width
        self.note = note

    def names(self):
        return [self.name]

    def widths_asserted(self):
        return [(self.name, self.width)] if self.width else []

    def arrays(self, entry, ident):
        return []

    def inits(self, entry, ident):
        return [
            (
                self.name,
                self.render(self.get(entry)),
                self.note(entry) if self.note else "",
            )
        ]

    def widths(self, entry, where, errors):
        if self.check:
            self.check(where, self.name, self.get(entry), errors)


class _RawField(Scalar):
    def inits(self, entry, ident):
        return [(self.name, self.get(entry, ident), "")]


class Arr:
    """A list-valued field: the pointer, its uint8_t count, and the static array the
    pointer names, all from one declaration. @p count is None for a list whose length
    another field already carries."""

    def __init__(self, name, elem_type, get, element, prefix, count):
        self.name = name
        self.elem_type = elem_type
        self.get = get
        self.element = element
        self.prefix = prefix
        self.count = count

    def symbol(self, ident):
        return f"{self.prefix}_{ident}"

    def names(self):
        return [self.name] + ([self.count] if self.count else [])

    def widths_asserted(self):
        return [(self.count, 1)] if self.count else []

    def arrays(self, entry, ident):
        items = self.get(entry)
        if not items:
            return []
        rendered = ", ".join(self.element(i) for i in items)
        return [f"static {self.elem_type} {self.symbol(ident)}[] = {{{rendered}}};"]

    def inits(self, entry, ident):
        items = self.get(entry)
        inits = [(self.name, self.symbol(ident) if items else "NULL", "")]
        if self.count:
            inits.append((self.count, str(len(items)), ""))
        return inits

    def widths(self, entry, where, errors):
        check_count(where, self.name, len(self.get(entry)), errors)


class Ref(Arr):
    """A list-valued field whose array is emitted by hand, because its elements carry
    sub-arrays of their own and so are not a pure function of one item."""

    def arrays(self, entry, ident):
        return []


def Str(name, get):
    return Scalar(name, get, _quoted)


def U32(name, get, render=_hex4, note=None):
    return Scalar(name, get, render, width=4, note=note)


def I32(name, get):
    return Scalar(name, get, check=check_i32, width=4)


def U8(name, get, note=None):
    return Scalar(name, get, check=check_u8, width=1, note=note)


def Enum(name, get):
    return Scalar(name, get, width=1)


def Flag(name, get):
    """A 1-bit field: no size assertion, sizeof does not apply to a bitfield."""
    return Scalar(name, get, _boolean)


def Raw(name, get):
    """Escape hatch for a field the descriptors cannot describe (the transform union):
    @p get renders the initialiser itself, and is passed the entry's C identifier."""
    return _RawField(name, get)


class Struct:
    """How to fill one table type declared in rm_mirror_mapping.h."""

    def __init__(self, c_name, fields):
        self.c_name = c_name
        self.fields = fields

    def names(self):
        """Every field this generator fills, as rm_mirror_mapping.h must declare them."""
        return [name for field in self.fields for name in field.names()]

    def assertions(self):
        """One size assertion per field, so a width changed in the hand-written header
        without its descriptor fails the build instead of truncating a value."""
        return [
            f"RM_MIRROR_STATIC_ASSERT(sizeof((({self.c_name} *)0)->{name}) == {width},\n"
            f'                        "{self.c_name}.{name} is not {width} byte(s): '
            f'gen_mapping_table.py assumes it is");'
            for field in self.fields
            for name, width in field.widths_asserted()
        ]

    def arrays(self, entry, ident):
        return [line for f in self.fields for line in f.arrays(entry, ident)]

    def row(self, entry, ident, indent="    "):
        lines = [indent + "{"]
        for field in self.fields:
            for name, value, note in field.inits(entry, ident):
                lines.append(
                    f"{indent}    .{name} = {value},{f' /* {note} */' if note else ''}"
                )
        lines.append(indent + "},")
        return lines

    def inline(self, entry, ident, suffix=""):
        """The entry as a one-line initialiser, for an element of a static array."""
        inits = [i for f in self.fields for i in f.inits(entry, ident)]
        text = "{" + ", ".join(f".{n} = {v}" for n, v, _ in inits) + "}" + suffix
        notes = [n for _, _, n in inits if n]
        return f"{text} /* {notes[0]} */" if notes else text

    def widths(self, entry, where, errors):
        for field in self.fields:
            try:
                field.widths(entry, where, errors)
            except (KeyError, ValueError, TypeError):
                pass  # malformed entry: the structural checks in validate() report it


